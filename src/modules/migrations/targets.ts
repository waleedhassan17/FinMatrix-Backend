import { MigrationEntityType } from './entities/migration-staging-row.entity';

/**
 * The target schema every source is mapped INTO: the eight sheets of the
 * starter workbook (§1.5). One list drives the template the server hands out,
 * the sheet and column detection, the AI assistant's `get_target_schema`
 * tool and the normaliser — so they cannot drift apart.
 *
 * Synonyms are header spellings people actually use, in English, Roman Urdu
 * and Urdu, plus what Tally, Peachtree, QuickBooks and Xero call the same
 * column. They are compared after normalizeKey(), so case, spaces,
 * punctuation and a trailing `*` never matter.
 */
export type FieldKind =
  | 'text'
  | 'code'
  | 'amount'
  | 'quantity'
  | 'date'
  | 'enum';

export interface TargetField {
  key: string;
  /** Exactly as written in the starter workbook's header row. */
  header: string;
  required?: boolean;
  kind: FieldKind;
  /** Canonical values for an enum field; mapped through VALUE_SYNONYMS. */
  enumValues?: readonly string[];
  synonyms: readonly string[];
  description: string;
  descriptionUr: string;
  example: string | number;
}

export interface TargetSheet {
  key: MigrationEntityType;
  /** Exactly as the starter workbook names the sheet. */
  name: string;
  synonyms: readonly string[];
  /** Field keys whose headers, found together, identify this sheet. */
  signature: readonly string[];
  fields: readonly TargetField[];
  purpose: string;
  purposeUr: string;
}

