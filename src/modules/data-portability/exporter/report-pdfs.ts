import { Injectable } from '@nestjs/common';
import Decimal from 'decimal.js';
import { companyForPdf, pdfDate } from '../../../common/pdf/document-pdf.util';
import {
  renderReportPdf,
  ReportPdfColumn,
  ReportPdfModel,
} from '../../../common/pdf/report-table-pdf.util';
import { toDecimal } from '../../../common/utils/money.util';
import { Company } from '../../companies/entities/company.entity';
import { ReportsService } from '../../reports/reports.service';
import { BalanceSheetLine, PnlLine } from '../../reports/reports.types';

/** The movement trial balance as ReportsService.trialBalance returns it. */
export interface TrialBalanceSnapshot {
  rows: Array<{
    accountCode: string;
    accountName: string;
    debit: number;
    credit: number;
  }>;
  totalDebits: number;
  totalCredits: number;
  isBalanced: boolean;
}

export interface ReportPdfFile {
  name: string;
  buffer: Buffer;
}

interface AgingRow {
  current: number;
  bucket1to30: number;
  bucket31to60: number;
  bucket61to90: number;
  bucket90Plus: number;
  total: number;
  [key: string]: unknown;
}

/** `1,234,567.89`; negatives with a leading minus. Decimal in, text out. */
export function fmtAmount(value: number | string | Decimal): string {
  const d = toDecimal(value);
  const fixed = d.abs().toFixed(2);
  const [whole, frac] = fixed.split('.');
  const grouped = whole.replace(/\B(?=(\d{3})+(?!\d))/g, ',');
  return `${d.isNegative() && !d.isZero() ? '-' : ''}${grouped}.${frac}`;
}

const CODE_NAME_AMOUNT: ReportPdfColumn[] = [
  { header: 'Account', width: 0.14 },
  { header: 'Name', width: 0.56 },
  { header: 'Amount', width: 0.3, align: 'right' },
];

/**
 * The five report PDFs inside a backup, each from the same ReportsService
 * method the app's own report screens call — so the PDF in the ZIP is the
 * report the owner sees, not a second calculation.
 */
@Injectable()
export class ExportReportPdfs {
  constructor(private readonly reports: ReportsService) {}

  async build(input: {
    company: Company;
    asOf: string;
    fiscalYearStart: string;
    trialBalance: TrialBalanceSnapshot;
  }): Promise<ReportPdfFile[]> {
    const { company, asOf } = input;
    const companyId = company.id;
    const pc = companyForPdf(company);
    const letterhead = {
      name: pc.name,
      lines: [...pc.addressLines, ...pc.contactLines],
    };
    const footer = `Generated by FinMatrix on ${pdfDate(new Date())} · ${company.name}`;
    const currency = company.homeCurrency ?? 'PKR';
    const meta = [{ label: 'Currency', value: currency }];

    const [balanceSheet, profitLoss, arAging, apAging] = await Promise.all([
      this.reports.balanceSheet(companyId, asOf),
      this.reports.profitLoss(companyId, input.fiscalYearStart, asOf),
      this.reports.arAging(companyId),
      this.reports.apAging(companyId),
    ]);

    const trialBalance: ReportPdfModel = {
      title: 'Trial Balance',
      subtitle: `As at ${pdfDate(asOf)}`,
      company: letterhead,
      meta,
      sections: [
        {
          columns: [
            { header: 'Account', width: 0.12 },
            { header: 'Name', width: 0.48 },
            { header: 'Debit', width: 0.2, align: 'right' },
            { header: 'Credit', width: 0.2, align: 'right' },
          ],
          rows: input.trialBalance.rows.map((r) => [
            r.accountCode,
            r.accountName,
            r.debit ? fmtAmount(r.debit) : '',
            r.credit ? fmtAmount(r.credit) : '',
          ]),
          totals: [
            [
              '',
              'Total',
              fmtAmount(input.trialBalance.totalDebits),
              fmtAmount(input.trialBalance.totalCredits),
            ],
          ],
          note: input.trialBalance.isBalanced
            ? 'Debits equal credits.'
            : 'WARNING: debits and credits do not agree.',
        },
      ],
      footer,
    };

    const bsSection = (
      heading: string,
      lines: BalanceSheetLine[],
      total: number,
    ) => ({
      heading,
      columns: CODE_NAME_AMOUNT,
      rows: lines.map((l) => [
        l.accountCode,
        l.accountName,
        fmtAmount(l.amount),
      ]),
      totals: [['', `Total ${heading.toLowerCase()}`, fmtAmount(total)]],
    });
    const balanceSheetModel: ReportPdfModel = {
      title: 'Balance Sheet',
      subtitle: `As at ${pdfDate(asOf)}`,
      company: letterhead,
      meta,
      sections: [
        bsSection('Assets', balanceSheet.assets, balanceSheet.totalAssets),
        bsSection(
          'Liabilities',
          balanceSheet.liabilities,
          balanceSheet.totalLiabilities,
        ),
        {
          ...bsSection('Equity', balanceSheet.equity, balanceSheet.totalEquity),
          totals: [
            ['', 'Total equity', fmtAmount(balanceSheet.totalEquity)],
            [
              '',
              'Total liabilities and equity',
              fmtAmount(balanceSheet.totalLiabilitiesAndEquity),
            ],
          ],
          note: balanceSheet.isBalanced
            ? 'Assets equal liabilities plus equity.'
            : `WARNING: assets differ from liabilities plus equity by ${fmtAmount(balanceSheet.gap)}.`,
        },
      ],
      footer,
    };

    const plSection = (heading: string, lines: PnlLine[], total: number) => ({
      heading,
      columns: CODE_NAME_AMOUNT,
      rows: lines.map((l) => [
        l.accountCode,
        l.accountName,
        fmtAmount(l.amount),
      ]),
      totals: [['', `Total ${heading.toLowerCase()}`, fmtAmount(total)]],
    });
    const sum = (lines: PnlLine[]) =>
      lines
        .reduce((a, l) => a.plus(toDecimal(l.amount)), new Decimal(0))
        .toNumber();
    const profitLossModel: ReportPdfModel = {
      title: 'Profit and Loss',
      subtitle: `${pdfDate(input.fiscalYearStart)} to ${pdfDate(asOf)} (fiscal year to date)`,
      company: letterhead,
      meta,
      sections: [
        plSection('Income', profitLoss.income, sum(profitLoss.income)),
        plSection('Cost of goods sold', profitLoss.cogsLines, profitLoss.cogs),
        {
          heading: 'Gross profit',
          columns: CODE_NAME_AMOUNT,
          rows: [],
          totals: [['', 'Gross profit', fmtAmount(profitLoss.grossProfit)]],
        },
        plSection(
          'Expenses',
          profitLoss.expenseLines,
          sum(profitLoss.expenseLines),
        ),
        plSection(
          'Other income',
          profitLoss.otherIncome,
          sum(profitLoss.otherIncome),
        ),
        plSection(
          'Other expense',
          profitLoss.otherExpense,
          sum(profitLoss.otherExpense),
        ),
        {
          heading: 'Net income',
          columns: CODE_NAME_AMOUNT,
          rows: [],
          totals: [
            ['', 'Total revenue', fmtAmount(profitLoss.revenue)],
            [
              '',
              'Total expenses (incl. COGS)',
              fmtAmount(
                toDecimal(profitLoss.expenses).plus(toDecimal(profitLoss.cogs)),
              ),
            ],
            ['', 'Net income', fmtAmount(profitLoss.netIncome)],
          ],
        },
      ],
      footer,
    };

    const agingModel = (
      title: string,
      party: string,
      nameKey: string,
      report: { asOfDate: string; rows: AgingRow[]; totals: AgingRow },
    ): ReportPdfModel => ({
      title,
      subtitle: `As at ${pdfDate(report.asOfDate)}`,
      company: letterhead,
      meta,
      sections: [
        {
          columns: [
            { header: party, width: 0.28 },
            { header: 'Current', width: 0.12, align: 'right' },
            { header: '1–30', width: 0.12, align: 'right' },
            { header: '31–60', width: 0.12, align: 'right' },
            { header: '61–90', width: 0.12, align: 'right' },
            { header: '90+', width: 0.12, align: 'right' },
            { header: 'Total', width: 0.12, align: 'right' },
          ],
          rows: report.rows.map((r) => [
            String(r[nameKey] ?? ''),
            fmtAmount(r.current),
            fmtAmount(r.bucket1to30),
            fmtAmount(r.bucket31to60),
            fmtAmount(r.bucket61to90),
            fmtAmount(r.bucket90Plus),
            fmtAmount(r.total),
          ]),
          totals: [
            [
              'Total',
              fmtAmount(report.totals.current),
              fmtAmount(report.totals.bucket1to30),
              fmtAmount(report.totals.bucket31to60),
              fmtAmount(report.totals.bucket61to90),
              fmtAmount(report.totals.bucket90Plus),
              fmtAmount(report.totals.total),
            ],
          ],
        },
      ],
      footer,
    });

    const files: ReportPdfFile[] = [
      {
        name: 'trial-balance.pdf',
        buffer: await renderReportPdf(trialBalance),
      },
      {
        name: 'balance-sheet.pdf',
        buffer: await renderReportPdf(balanceSheetModel),
      },
      {
        name: 'profit-and-loss.pdf',
        buffer: await renderReportPdf(profitLossModel),
      },
      {
        name: 'ar-aging.pdf',
        buffer: await renderReportPdf(
          agingModel(
            'Accounts Receivable Aging',
            'Customer',
            'customerName',
            arAging as never,
          ),
        ),
      },
      {
        name: 'ap-aging.pdf',
        buffer: await renderReportPdf(
          agingModel(
            'Accounts Payable Aging',
            'Vendor',
            'vendorName',
            apAging as never,
          ),
        ),
      },
    ];
    return files;
  }
}
